from __future__ import annotations

from enum import StrEnum


class TransactionStatus(StrEnum):
    PROPOSED = "PROPOSED"
    POLICY_REVIEW = "POLICY_REVIEW"
    RISK_REVIEW = "RISK_REVIEW"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    APPROVED = "APPROVED"
    DENIED = "DENIED"
    BLOCKED = "BLOCKED"
    PAYMENT_CREATED = "PAYMENT_CREATED"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


# Statuses whose amount counts against daily / monthly spending limits.
COMMITTED_STATUSES = (
    TransactionStatus.APPROVED,
    TransactionStatus.PAYMENT_CREATED,
    TransactionStatus.COMPLETED,
)


class Decision(StrEnum):
    ALLOW = "ALLOW"
    DENY = "DENY"
    HUMAN_APPROVAL_REQUIRED = "HUMAN_APPROVAL_REQUIRED"


class FinalDecision(StrEnum):
    """Outcome of the approval engine, which combines shield, risk and policy."""

    ALLOW = "ALLOW"
    HUMAN_APPROVAL_REQUIRED = "HUMAN_APPROVAL_REQUIRED"
    DENY = "DENY"  # policy violation
    BLOCK = "BLOCK"  # security / risk / fail-closed


class ApprovalStatus(StrEnum):
    NOT_REQUIRED = "NOT_REQUIRED"
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    DENIED = "DENIED"


class RiskLevel(StrEnum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class VerificationStatus(StrEnum):
    VERIFIED = "VERIFIED"
    PENDING = "PENDING"
    UNVERIFIED = "UNVERIFIED"
    FLAGGED = "FLAGGED"


class EventType(StrEnum):
    INTENT_RECEIVED = "INTENT_RECEIVED"
    AGENT_STARTED = "AGENT_STARTED"
    MERCHANT_FOUND = "MERCHANT_FOUND"
    TRANSACTION_PROPOSED = "TRANSACTION_PROPOSED"
    MERCHANT_ANALYZED = "MERCHANT_ANALYZED"
    SECURITY_SCANNED = "SECURITY_SCANNED"
    PROMPT_INJECTION_DETECTED = "PROMPT_INJECTION_DETECTED"
    RISK_ASSESSED = "RISK_ASSESSED"
    POLICY_EVALUATED = "POLICY_EVALUATED"
    DECISION_MADE = "DECISION_MADE"
    APPROVAL_REQUESTED = "APPROVAL_REQUESTED"
    APPROVED = "APPROVED"
    DENIED = "DENIED"
    PAYPAL_ORDER_CREATED = "PAYPAL_ORDER_CREATED"
    PAYPAL_PAYMENT_CAPTURED = "PAYPAL_PAYMENT_CAPTURED"
    PAYMENT_FAILED = "PAYMENT_FAILED"
    TRANSACTION_COMPLETED = "TRANSACTION_COMPLETED"
    TRANSACTION_BLOCKED = "TRANSACTION_BLOCKED"
    TRANSACTION_DENIED = "TRANSACTION_DENIED"
    FAIL_CLOSED = "FAIL_CLOSED"
    POLICY_UPDATED = "POLICY_UPDATED"


class ThreatType(StrEnum):
    PROMPT_INJECTION = "PROMPT_INJECTION"
    SPENDING_VIOLATION = "SPENDING_VIOLATION"
    SUSPICIOUS_MERCHANT = "SUSPICIOUS_MERCHANT"
    UNUSUAL_TRANSACTION = "UNUSUAL_TRANSACTION"
    POLICY_VIOLATION = "POLICY_VIOLATION"
    SYSTEM_FAILURE = "SYSTEM_FAILURE"


class Severity(StrEnum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"
